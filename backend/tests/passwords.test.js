import assert from 'node:assert/strict';
import { test } from 'node:test';
import bcrypt from 'bcryptjs';
import { isBcryptPasswordHash } from '../lib/passwords.js';

test('recognizes hashes generated by bcryptjs', async () => {
    const hash = await bcrypt.hash('test-password', 4);

    assert.equal(isBcryptPasswordHash(hash), true);
    assert.equal(await bcrypt.compare('test-password', hash), true);
});

test('does not treat plaintext or unsupported hash formats as bcrypt', () => {
    assert.equal(isBcryptPasswordHash('legacy-password'), false);
    assert.equal(isBcryptPasswordHash('$2x$12$unsupported'), false);
    assert.equal(isBcryptPasswordHash('$2b$12$malformed'), false);
    assert.equal(isBcryptPasswordHash(null), false);
});
